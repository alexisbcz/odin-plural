#!/usr/bin/env python3
"""Generate small GNU gettext .mo catalogs for the tests and the gettext example.

Writes tests/mo_fixtures_test.odin (the catalogs as byte arrays) and
examples/gettext/ru.mo (the Russian catalog as a file).

Each catalog holds a header and one plural message, msgid "file" with
msgid_plural "files", translated into every plural form of its language.
The plural form order is the CLDR order that plural.i18n_pluralizer uses.

Usage:

    python3 tools/gen_mo_fixtures.py
"""

from __future__ import annotations

import os
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CATALOGS = {
    "ru": ("nplurals=3", ["файл", "файла", "файлов"]),
    "pl": ("nplurals=3", ["plik", "pliki", "plików"]),
    "ar": ("nplurals=6", ["لا ملفات", "ملف واحد", "ملفان", "ملفات", "ملفًا", "ملف"]),
    "fr": ("nplurals=2", ["fichier", "fichiers"]),
}


def build_mo(entries: dict[bytes, bytes]) -> bytes:
    """Build a little-endian .mo file (revision 0) without a hash table."""
    keys = sorted(entries)
    n = len(keys)
    header_size = 7 * 4
    originals_at = header_size
    translations_at = originals_at + n * 8
    data_at = translations_at + n * 8

    blob = b""
    originals, translations = [], []
    for key in keys:
        originals.append((len(key), data_at + len(blob)))
        blob += key + b"\0"
    for key in keys:
        value = entries[key]
        translations.append((len(value), data_at + len(blob)))
        blob += value + b"\0"

    out = struct.pack("<7I", 0x950412DE, 0, n, originals_at, translations_at, 0, 0)
    for length, offset in originals + translations:
        out += struct.pack("<2I", length, offset)
    return out + blob


def odin_bytes(data: bytes) -> list[str]:
    lines = []
    for start in range(0, len(data), 16):
        chunk = data[start : start + 16]
        lines.append("\t" + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    return lines


def main() -> None:
    catalogs: dict[str, bytes] = {}
    out = [
        "// Code generated by tools/gen_mo_fixtures.py. DO NOT EDIT.",
        "//",
        "// Each array is a complete GNU gettext .mo catalog with one plural message.",
        "package plural_tests",
        "",
    ]
    for lang, (nplurals, forms) in CATALOGS.items():
        header = (
            "Content-Type: text/plain; charset=UTF-8\n"
            f"Language: {lang}\n"
            f"Plural-Forms: {nplurals}; plural=(CLDR order);\n"
        )
        entries = {
            b"": header.encode(),
            b"file\0files": b"\0".join(f.encode() for f in forms),
            b"Hello": {"ru": "Привет", "pl": "Cześć", "ar": "مرحبا", "fr": "Bonjour"}[lang].encode(),
        }
        out.append(f"// MO_{lang.upper()} translates \"file\" as: {', '.join(forms)}.")
        out.append(f"MO_{lang.upper()} := [?]u8{{")
        catalogs[lang] = build_mo(entries)
        out.extend(odin_bytes(catalogs[lang]))
        out.append("}")
        out.append("")
    path = os.path.join(ROOT, "tests", "mo_fixtures_test.odin")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    with open(os.path.join(ROOT, "examples", "gettext", "ru.mo"), "wb") as f:
        f.write(catalogs["ru"])


if __name__ == "__main__":
    main()
